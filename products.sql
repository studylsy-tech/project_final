-- 1. 기존 테이블 및 제약 조건 삭제
DROP TABLE PRICE_HISTORY CASCADE CONSTRAINTS;
DROP TABLE Common_Product CASCADE CONSTRAINTS;

-- 2. 상품 기본 정보 테이블
-- PROD_ID: 시스템 내부 관리용 PK (숫자)
-- PROD_CODE: 비즈니스 고유 키 (UNIQUE 제약으로 중복 차단)
CREATE TABLE Common_Product (
    PROD_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, 
    PROD_CODE    VARCHAR2(50) NOT NULL,      
    SOURCE       VARCHAR2(50),               
    CATEGORY     VARCHAR2(50),               
    PROD_NAME    VARCHAR2(200) NOT NULL,     
    BRAND        VARCHAR2(100),              
    PROD_PRICE   NUMBER,                     
    TARGET_PRICE NUMBER,                    
    CHECK_INTERVAL NUMBER DEFAULT 6,         
    REG_DATE     DATE DEFAULT SYSDATE,
    -- PROD_CODE 중복을 DB 레벨에서 원천 봉쇄
    CONSTRAINT UK_PROD_CODE UNIQUE (PROD_CODE)
);

-- 3. 가격 변동 이력 테이블
CREATE TABLE PRICE_HISTORY (
    HIST_ID      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PROD_ID      NUMBER NOT NULL,            
    PRICE        NUMBER NOT NULL,            
    REG_DATE     DATE DEFAULT SYSDATE,       
    CONSTRAINT FK_HIST_PROD_ID FOREIGN KEY (PROD_ID) 
    REFERENCES Common_Product(PROD_ID) ON DELETE CASCADE
);

