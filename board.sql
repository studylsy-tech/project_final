--0. 테이블 삭제
DROP TABLE BOARD;

-- 1. 공지사항 테이블 (NOTICE)
CREATE TABLE BOARD (
NOTICE_NO     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
TITLE         VARCHAR2(200) NOT NULL,
CONTENT       CLOB          NOT NULL,
WRITER        VARCHAR2(50)  NOT NULL, -- 작성자 (NICKNAME 또는 PHONE)
BOARD_TYPE    VARCHAR2(20)  NOT NULL, -- 게시판 구분 ('NOTICE', 'QNA')
COUNT         NUMBER DEFAULT 0,      -- 조회수
INDATE        DATE DEFAULT SYSDATE   -- 작성일
);


