-- 1. 기존 테이블 삭제
DROP TABLE BOARD;

-- 2. 새 구조로 생성 (PARENT_NO, IS_REPLY 포함)
CREATE TABLE BOARD (
    NOTICE_NO    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    TITLE        VARCHAR2(200) NOT NULL,
    CONTENT      CLOB          NOT NULL,
    WRITER       VARCHAR2(50)  NOT NULL,
    BOARD_TYPE   VARCHAR2(20)  NOT NULL, -- 'NOTICE', 'QNA'
    COUNT        NUMBER DEFAULT 0,
    INDATE       DATE DEFAULT SYSDATE,   -- 작성일 (시간 포함)
    PARENT_NO    NUMBER DEFAULT 0,       -- 원글 번호 (0: 질문, n: 답변일 때 원글번호)
    IS_REPLY     NUMBER DEFAULT 0        -- 답변 여부 (0: 질문, 1: 답변)
);

-- 3. 테스트 데이터 (질문 100개) 생성
BEGIN
    FOR i IN 1..100 LOOP
        INSERT INTO BOARD (TITLE, CONTENT, WRITER, BOARD_TYPE, PARENT_NO, IS_REPLY)
        VALUES ('질문 테스트 ' || i, '내용 ' || i, '작성자' || i, 'QNA', 0, 0);
    END LOOP;
    COMMIT;
END;
/
-- 4. 공지사항 데이터 101건 삽입 SQL
BEGIN
    FOR i IN 1..101 LOOP
        INSERT INTO BOARD (
            TITLE, 
            CONTENT, 
            WRITER, 
            BOARD_TYPE, 
            PARENT_NO, 
            IS_REPLY
        )
        VALUES (
            '공지사항 테스트 제목 ' || i, 
            '공지사항 테스트 내용입니다. 번호: ' || i, 
            '관리자', 
            'NOTICE', 
            0, 
            0
        );
    END LOOP;
    COMMIT;
END;
/
SELECT NOTICE_NO, TITLE, PARENT_NO, IS_REPLY FROM BOARD WHERE NOTICE_NO >= 99;