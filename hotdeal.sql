-- 테이블 삭제 명령어
DROP TABLE TB_PRICE_HISTORY;
DROP TABLE TB_HOTDEAL_TRACKER;

-- 핫딜 메인 테이블
CREATE TABLE TB_HOTDEAL_TRACKER (
    DEAL_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ORIGIN_URL VARCHAR2(500) UNIQUE, 
    TITLE VARCHAR2(300),
    CURRENT_PRICE NUMBER,
    START_PRICE NUMBER,              
    MALL_NAME VARCHAR2(100),         
    COMMUNITY_NAME VARCHAR2(100),    
    LAST_UPDATE_DATE DATE DEFAULT SYSDATE
);

-- 가격 변동 이력 테이블
CREATE TABLE TB_PRICE_HISTORY (
    HISTORY_ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DEAL_ID NUMBER REFERENCES TB_HOTDEAL_TRACKER(DEAL_ID) ON DELETE CASCADE,
    PRICE NUMBER,
    RECORD_DATE DATE DEFAULT SYSDATE
);

SELECT * FROM TB_HOTDEAL_TRACKER ORDER BY LAST_UPDATE_DATE DESC;